"""What happens when you stack many sleeves that each beat the benchmark 55% of the time.

The proposition this module scores, in the investor's own words: *"if you stack a ton of
strategies that are 55% likely to beat the market then you will beat the market."*

**It is conditionally true and conditionally false, and one number decides which.** The
arithmetic below is elementary and has no free parameters, so the whole disagreement
reduces to two measurable inputs — the correlation of the sleeves' *excess* returns, and
whether the sleeves are funded from the same capital or financed on top of it.

The three results, stated before the code that produces them.

**1. Probability tracks the information ratio, and the information ratio tracks
*effective* breadth, not sleeve count.** For sleeves with excess-return vector ``e``,
weights ``w`` and excess covariance ``Sigma``,

    IR = w'e / sqrt(w' Sigma w),      P(ahead after T years) = Phi(IR sqrt(T))

which is :mod:`portfolio_edge.studies.outperformance_horizon` with ``e/s`` renamed. For
``k`` sleeves of identical edge, identical tracking error and mutual correlation ``rho``,
``IR = IR_1 sqrt(k / (1 + (k-1) rho))`` — the *same* ``k / (1 + (k-1) rho)`` that
:func:`portfolio_edge.studies.overlay_growth.effective_breadth` already defines. So

    P_k = Phi( z_1 sqrt(effective breadth) ),    z_1 = Phi^-1(P_1).

**2. Stacking has a ceiling, and at realistic correlations it is close.** Effective
breadth converges to ``1/rho`` as ``k`` grows, so

    P_infinity = Phi( z_1 / sqrt(rho) )

**however many sleeves are stacked**. At ``P_1 = 0.55`` and ``rho = 0.4`` an infinite
stack reaches 0.578. The investor's intuition — that enough 55% bets compound into a
near-certainty — is the ``rho = 0`` limit of this expression and nothing else.

**3. Funding decides whether "stack" means add or average.** Under a fixed capital base
the weights sum to at most one, so portfolio edge is a weighted *average* of sleeve edges
and is bounded above by the single best sleeve — adding a sleeve raises effective breadth
and lowers mean edge at the same time. Under a financed overlay the weights are notional
and unconstrained, so portfolio edge is a *sum*. **The thesis is a statement about
overlays being applied to a substitution portfolio**, and
[capital efficiency](../../../../docs/research/capital-efficiency-and-breadth.md) already
measures the gap between the two funding rules at 2.44 pp/yr for a 100%-equity base.

Two things this module deliberately does not do. It does not estimate any premium: every
edge is an input, because the same repository that can resolve a correlation to two
decimals cannot sign most of these premia
([evidence base](../../../../docs/research/evidence-base.md) §1). And it never multiplies
a factor loading by a long-only capture fraction — the sleeve edges it consumes are built
by :mod:`portfolio_edge.studies.value_tilt`, which raises on that error.

Units throughout are **percentage points a year**, matching
:mod:`portfolio_edge.studies.value_tilt`: a 4.74 pp/yr premium is ``4.74``. Weights are
fractions. The one conversion is into
:mod:`portfolio_edge.studies.outperformance_horizon`, which works in basis points.

Nothing here reads market data; the caller supplies edges and a covariance matrix. The
measured tables are regenerated by :mod:`portfolio_edge.studies._stacking_tables`.
"""

