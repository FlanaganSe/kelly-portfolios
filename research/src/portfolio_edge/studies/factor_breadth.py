"""Do the factor families this repository never examined add an *engine*?

[Decision 0005](../../../../docs/decisions/0005-factor-premia-closed-on-public-data.md)
closed factor work "on public data" on the strength of five families — HML, RMW, CMA,
UMD, SMB — against the eighteen in :data:`EQUITY_FACTOR_FAMILIES`. Seven of the untested ones
have free monthly data already reachable from the adapters in
:mod:`portfolio_edge.data`: betting against beta, quality, short- and long-term
reversal, accruals, net issuance, and the unlevered low-beta decile spread. This
module is the arithmetic that scores them.

**The question is breadth, not premia, and the two have very different resolution.**
A premium is a mean, and [the evidence base](../../../../docs/research/evidence-base.md)
§1 measures this library's floor for one at 2.62 pp/yr pooled and 5.0 pp/yr for a
single US post-publication window — above the 2.0 pp/yr that would matter. A
correlation is not a mean. Over 700 monthly observations a correlation near zero has a
standard error near ``1/sqrt(700) = 0.038``, so the *same files that cannot sign a
premium can resolve a correlation to two decimal places*. That asymmetry is why this
module reports both and why the conclusions it licenses are about the correlation
matrix rather than about any expected return.

**What clears, clears as an overlay.** Admission is equation (4) of
:mod:`portfolio_edge.studies.overlay_growth`, ``S_d > L rho sigma_p``, and that module's
own warning applies here with force: the condition is a first-order statement at
``w = 0`` and is **not** a decision rule above roughly ``|rho| = 0.5``. The unlevered
low-beta decile spread sits well past that boundary and is scored, and reported, as
inadmissible-to-this-test rather than as passing or failing it.

**Three properties of the inputs decide how far any of it may be read.**

*They are gross long-short academic portfolios.* Every series here is
zero-net-investment, has no fee, no spread, no borrow, no capacity and no tax, and the
short leg is assumed free. A premium is not a sleeve; a sleeve needs a vehicle, and
whether one exists is a fact about the fund shelf rather than about the premium.

*Two of them are vendor reconstructions by a firm that sells the strategy.* The BAB
and QMJ workbooks are rebuilt from scratch on every update, publish no vintage archive
and state no cost basis anywhere — the same flags the time-series-momentum file carries
and the same reason [Experiment 011](../../../experiments/exp_011_overlay_stack.yaml)
returned ``unresolved``.

*Three of them do not exist as published factors at all.* Ken French distributes
sorted portfolios for net issuance, accruals and prior beta but no long-short factor
file for any of them, so those three spreads are **this repository's construction**.
They inherit no external replication and must never be quoted as "the Ken French
accruals factor".

Nothing here reads market data; the caller supplies aligned arrays. The tables are
regenerated by :mod:`portfolio_edge.studies._factor_breadth_tables`.
"""

